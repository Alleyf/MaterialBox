export async function getLanguage() {
  const stored = await extensionApi.storage.local.get("language");
  if (stored.language) {
    return stored.language;
  }
  const uiLanguage = extensionApi.i18n?.getUILanguage?.() ?? "en";
  return uiLanguage.toLowerCase().startsWith("zh") ? "zh" : "en";
}

export async function setLanguage(language) {
  await extensionApi.storage.local.set({ language });
}

export function t(language, key, params = {}) {
  const template = DICTIONARY[language]?.[key] ?? DICTIONARY.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, token) => String(params[token] ?? ""));
}

export function getCategoryOptions(language) {
  return CATEGORY_ORDER.map((key) => ({
    value: key,
    label: t(language, key)
  }));
}
